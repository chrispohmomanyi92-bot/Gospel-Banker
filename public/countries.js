const NAMES = new Map(COUNTRIES);
export const isCountry = (code) => NAMES.has(code);
export const countryName = (code) => NAMES.get(code) || '';
// Flag emoji from the two-letter code (shown as letters on systems without flag emoji).
export const flag = (code) => (code ? String.fromCodePoint(...[...code].map((c) => 127397 + c.charCodeAt(0))) : '');
export const countryLabel = (code) => (code ? `${flag(code)} ${countryName(code)}` : '');
// <option> list for a <select>. Countries a store owner is most likely in come first.
export function countryOptions(selected = '', first = ['KE', 'UG', 'TZ', 'RW', 'BI', 'ET', 'NG', 'GH', 'ZA', 'ZM', 'ZW', 'MW', 'CD', 'SS']) {
  const inFirst = first.includes(selected);
  const opt = (sel) => ([c, n]) => `<option value="${c}" ${sel && c === selected ? 'selected' : ''}>${flag(c)} ${n.replace(/&/g, '&amp;')}</option>`;
  return `<optgroup label="Common">${first.map((c) => opt(inFirst)([c, NAMES.get(c)])).join('')}</optgroup>`
    + `<optgroup label="All countries">${COUNTRIES.map(opt(!inFirst)).join('')}</optgroup>`;
}

